<?php

namespace App\Jobs;

use App\Models\HelperModel;
use App\Models\User;
use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Bus\Dispatchable;
use Illuminate\Queue\InteractsWithQueue;
use Illuminate\Queue\SerializesModels;

class NotifyUserImageDeclined implements ShouldQueue
{
    use Dispatchable, InteractsWithQueue, Queueable, SerializesModels;

    protected $userId;

    /**
     * Create a new job instance.
     *
     * @param $userId
     * @return void
     */
    public function __construct($userId)
    {
        $this->userId = $userId;
    }

    /**
     * Execute the job.
     *
     * @return void
     */
    public function handle()
    {
        // Query the User.
        $user = User::find($this->userId);

        // If the User exists, set app localization to users' last language.
        if ($user) {
            app()->setLocale($user->last_language);
        }

        $data = [
            'user_id'               => $this->userId ,
            'notification_value'    => $this->userId,
            'type'                  => __('NOTIFICATION_USER_IMAGE_DECLINED'),
            'notification_title'    => __('NOTIFICATION_USER_IMAGE_DECLINED_TITLE'),
            'notification_body'     => __('NOTIFICATION_USER_IMAGE_DECLINED_BODY'),
        ];

        HelperModel::sendPushNotification($data);
    }
}
